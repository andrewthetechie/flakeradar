//! The mismatches a replay may accept, and their reconciliation with the record.
//!
//! `tests/parity/allowed-differences.json` names every difference a replayed
//! golden may show, and `docs/plans/rust-rewrite/differences.md` explains each
//! one. The replay reads the first through [`Allowances`]; the reconciliation in
//! [`reconcile`] checks that the two files still say the same thing, which is
//! what the deleted recorder used to do. Nothing here runs a server: the checks
//! are over committed files.
//
// Rust guideline compliant 2026-07-21

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Deserializer};
use serde_json::Value;

/// One entry of `tests/parity/allowed-differences.json`.
#[derive(Debug, Deserialize)]
pub(crate) struct Allowance {
    /// The entry's name, unique within the file.
    pub(crate) id: String,
    /// The headline of the `differences.md` row the entry cites.
    #[serde(rename = "differenceRow")]
    difference_row: String,
    /// Why the difference is intended, for a reader of the fixture.
    #[serde(default)]
    reason: String,
    /// The golden fields the entry covers.
    pub(crate) allows: Vec<AllowedField>,
}

/// One golden field an allowance covers, and what may differ there.
#[derive(Debug, Deserialize)]
pub(crate) struct AllowedField {
    /// The golden the field belongs to, relative to `tests/parity`.
    pub(crate) file: String,
    /// The dotted path into the golden, such as `body.detail`.
    pub(crate) field: String,
    /// The value Python recorded there, when the allowance is narrowed to it.
    ///
    /// An explicit `null` is a named value — the field the golden does not carry
    /// — so it is not the same thing as the key being absent.
    #[serde(rename = "pythonValue", default, deserialize_with = "named")]
    pub(crate) python_value: Option<Value>,
    /// The value the Rust server answers, when the allowance is narrowed to it.
    #[serde(rename = "rustValue", default, deserialize_with = "named")]
    pub(crate) rust_value: Option<Value>,
    /// A contract the field carries, which is compared by its promises rather
    /// than by value.
    pub(crate) contract: Option<ContractRule>,
}

/// One named value, where an explicit `null` is a value and absence is none.
///
/// # Errors
///
/// Returns the deserializer's error when the member is not JSON.
fn named<'de, D>(deserializer: D) -> Result<Option<Value>, D::Error>
where
    D: Deserializer<'de>,
{
    Value::deserialize(deserializer).map(Some)
}

/// A contract a field is compared by instead of value for value.
///
/// The only kind is `openapi`: `/openapi.json` is generated by two different
/// frameworks, so the documents cannot agree byte for byte, and the promise both
/// sides make is the one this comparison checks — the same paths, methods,
/// parameters, field types and required lists. The reason is in
/// `differences.md`.
#[derive(Debug, Deserialize)]
pub(crate) struct ContractRule {
    /// Which contract: `openapi` is the only kind.
    pub(crate) kind: String,
}

/// Every allowance the repository records.
#[derive(Debug)]
pub(crate) struct Allowances {
    /// The entries, in file order.
    entries: Vec<Allowance>,
}

impl Allowances {
    /// Reads `tests/parity/allowed-differences.json`.
    ///
    /// # Panics
    ///
    /// Panics when the fixture cannot be read or is not the documented shape: a
    /// test that cannot read its own contract has failed.
    pub(crate) fn load() -> Self {
        let path = root().join("allowed-differences.json");
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("reading {}: {error}", path.display()));
        let entries: Vec<Allowance> = serde_json::from_str(&text)
            .unwrap_or_else(|error| panic!("parsing {}: {error}", path.display()));
        Self { entries }
    }

    /// The golden fields that cover one replayed step.
    pub(crate) fn for_step(&self, scenario: &str, step: usize) -> Vec<&AllowedField> {
        let file = format!("golden/{scenario}/{step:02}.json");
        self.entries
            .iter()
            .flat_map(|entry| entry.allows.iter())
            .filter(|allowed| allowed.file == file)
            .collect()
    }

    /// The entries, for the reconciliation.
    pub(crate) fn entries(&self) -> &[Allowance] {
        &self.entries
    }
}

/// Whether an allowance covers `path` with exactly this mismatch.
pub(crate) fn allowed(
    path: &str,
    expected: &Value,
    actual: &Value,
    allowances: &[&AllowedField],
) -> bool {
    allowances.iter().any(|allowance| {
        allowance.field == path
            && allowance
                .python_value
                .as_ref()
                .is_none_or(|python_value| python_value == expected)
            && allowance
                .rust_value
                .as_ref()
                .is_none_or(|rust_value| rust_value == actual)
    })
}

/// The contract an allowance pins `path` to, if one does.
pub(crate) fn contract_for<'a>(path: &str, allowances: &'a [&AllowedField]) -> Option<&'a str> {
    allowances
        .iter()
        .filter(|allowance| allowance.field == path)
        .find_map(|allowance| allowance.contract.as_ref())
        .map(|rule| rule.kind.as_str())
}

/// The repository's `tests/parity` directory.
pub(crate) fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/parity")
}

/// The committed `differences.md`.
///
/// # Panics
///
/// Panics when the file cannot be read: the reconciliation has nothing to
/// reconcile against.
pub(crate) fn differences() -> String {
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/plans/rust-rewrite/differences.md");
    std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("reading {}: {error}", path.display()))
}

/// Every problem the allowances have against the record, each named.
///
/// An allowance is honest only when all of this holds: its `differenceRow` is a
/// row of `differences.md`, the golden it names exists, the field it names holds
/// exactly the value it says Python recorded (an absent field is `null`), and it
/// narrows the difference to named values or to a contract — an entry that names
/// neither accepts any mismatch at that field, which is how a real regression
/// hides.
pub(crate) fn reconcile(entries: &[Allowance], differences: &str, parity: &Path) -> Vec<String> {
    let mut problems = Vec::new();
    let mut ids = BTreeSet::new();
    for entry in entries {
        if !ids.insert(entry.id.as_str()) {
            problems.push(format!("{}: the entry id is used twice", entry.id));
        }
        if entry.reason.trim().is_empty() {
            problems.push(format!("{}: the entry gives no reason", entry.id));
        }
        if !entry.difference_row.trim().is_empty()
            && !differences.contains(entry.difference_row.as_str())
        {
            problems.push(format!(
                "{}: {} is not a row of differences.md",
                entry.id, entry.difference_row
            ));
        }
        for allowed in &entry.allows {
            problems.extend(check_field(&entry.id, allowed, parity));
        }
    }
    problems
}

/// Every problem one allowance's field has, named by its golden and path.
fn check_field(id: &str, allowed: &AllowedField, parity: &Path) -> Vec<String> {
    let mut problems = Vec::new();
    let path = parity.join(&allowed.file);
    let Some(golden) = std::fs::read_to_string(&path)
        .ok()
        .and_then(|text| serde_json::from_str::<Value>(&text).ok())
    else {
        problems.push(format!("{id}: {} is not a readable golden", allowed.file));
        return problems;
    };
    if allowed.contract.is_some() {
        if allowed.python_value.is_some() || allowed.rust_value.is_some() {
            problems.push(format!(
                "{id}: {} {} is compared by a contract and must not name values",
                allowed.file, allowed.field
            ));
        }
        return problems;
    }
    let (Some(python_value), Some(_)) = (&allowed.python_value, &allowed.rust_value) else {
        problems.push(format!(
            "{id}: {} {} names the difference without the values it may show",
            allowed.file, allowed.field
        ));
        return problems;
    };
    // A field the golden does not carry is `null` on the wire, so an allowance
    // that narrows an absent field names `null` for it.
    let recorded = value_at(&golden, &allowed.field).unwrap_or(&Value::Null);
    if recorded != python_value {
        problems.push(format!(
            "{id}: {} {} recorded {recorded} where the entry says {python_value}",
            allowed.file, allowed.field
        ));
    }
    problems
}

/// The value a golden holds at a dotted path, if it holds one.
///
/// A numeric part indexes an array, so `cases.2.line` is the third case's line.
pub(crate) fn value_at<'a>(document: &'a Value, path: &str) -> Option<&'a Value> {
    let mut current = document;
    for part in path.split('.') {
        current = match current {
            Value::Object(fields) => fields.get(part)?,
            Value::Array(items) => items.get(part.parse::<usize>().ok()?)?,
            _ => return None,
        };
    }
    Some(current)
}
